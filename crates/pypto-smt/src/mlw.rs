//! WhyML emission: one `.mlw` module per spmd body — the model artifact
//! plus generated goals for the three checks.
//!
//! * the body is mirrored as declarations: uninterpreted `read_*`
//!   functions for the metadata plane, dimension symbols, and the
//!   stride-partition lemma;
//! * Q1/Q2 (cross-tile R-W / W-W overlap) become one quantified goal per
//!   unordered access pair — proved ⇔ disjoint under every admissible
//!   metadata valuation; unproved = race candidate;
//! * Q3 (output coverage) becomes one `forall datum, exists writer` goal
//!   per written region with literal dims; guards included, so a
//!   guarded store yields an honestly-unproved goal, not a fake proof.
//!
//! Sync constructs are ignored by scoping decision (possible false
//! positives); refused constructs never reach the emitter.

use std::fmt::Write;

use crate::consts as tool;
use crate::term::{BinOp, Bool, CmpOp, Term};
use crate::walk::{sanitize, Access, Dir, SpmdBody};

/// Copy letter: instance variable namespace for one side of a pair.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Copy {
    A,
    B,
}

impl Copy {
    // The copy letters are the encoding's own names (necessities).
    #[allow(inline_literal)]
    fn suffix(self) -> &'static str {
        match self {
            Copy::A => "a",
            Copy::B => "b",
        }
    }
}

/// Emits the WhyML module for one walked body.
pub fn emit_mlw(body: &SpmdBody, provenance: &str) -> String {
    let mut m = Module::new(body, provenance);
    m.header();
    m.decls();
    m.pair_goals();
    m.coverage_goals();
    m.finish()
}

struct Module<'a> {
    body: &'a SpmdBody,
    out: String,
    goal_seq: usize,
}

impl<'a> Module<'a> {
    fn new(body: &'a SpmdBody, provenance: &str) -> Self {
        let mut out = String::new();
        let _ = writeln!(out, "(* {provenance} *)");
        let _ = writeln!(out, "(* Generated by pypto-smt from a real PyPTO compiler dump. *)");
        let _ = writeln!(
            out,
            "(* Q1/Q2: cross-tile raw/waw with w_a <> w_b; synchronization ignored. *)"
        );
        Module {
            body,
            out,
            goal_seq: 0,
        }
    }

    // Why3 stdlib theory names are the tool's own vocabulary.
    #[allow(inline_literal)]
    fn header(&mut self) {
        let _ = writeln!(self.out, "module SpmdBody");
        for theory in ["int.Int", "int.MinMax", "int.ComputerDivision"] {
            let _ = writeln!(self.out, "  use {theory}");
        }
        let _ = writeln!(self.out);
    }

    fn decls(&mut self) {
        for (name, value) in &self.body.consts {
            let _ = writeln!(self.out, "  constant {name} : int = {value}");
        }
        for name in &self.body.symbols {
            let _ = writeln!(self.out, "  constant {name} : int");
        }
        if !self.body.consts.is_empty() || !self.body.symbols.is_empty() {
            let _ = writeln!(self.out);
        }
        for (func, arity) in &self.body.read_funcs {
            let args: Vec<String> = (0..*arity).map(|i| format!("x{i}")).collect();
            let params = if args.is_empty() {
                String::new()
            } else {
                format!("{} : int", args.join(" "))
            };
            let _ = writeln!(self.out, "  function {func} ({params}) : int");
        }
        if !self.body.read_funcs.is_empty() {
            let _ = writeln!(self.out);
        }
        let width = self.body.width;
        let _ = writeln!(
            self.out,
            "  lemma stride_partition : forall w1 w2 k1 k2. 0 <= w1 < {width} -> 0 <= w2 < {width} ->"
        );
        let _ = writeln!(
            self.out,
            "    w1 <> w2 -> k1 >= 0 -> k2 >= 0 -> w1 + {width} * k1 <> w2 + {width} * k2"
        );
        let _ = writeln!(self.out);
        let _ = writeln!(
            self.out,
            "  predicate overlap (o1 s1 o2 s2 : int) = o1 < o2 + s2 /\\ o2 < o1 + s1"
        );
        let _ = writeln!(self.out);
    }

    /// The loops an access's executing instance ranges over, as
    /// `(index, loop)` pairs in body order.
    fn loops_of(&self, access: &Access) -> Vec<(usize, &crate::walk::LoopInfo)> {
        self.body
            .loops
            .iter()
            .enumerate()
            .filter(|(_, l)| access.coords.contains(&l.var))
            .collect()
    }

    /// Quantifier variables and instance constraints for one copy of one
    /// access: the worker, one `k` per enclosing loop, and one free
    /// (havoced) variable per carried value in the writer's context —
    /// data-race detection havocs the whole context, so carries carry no
    /// constraints.
    fn instance(&self, access: &Access, copy: Copy) -> (Vec<String>, Vec<String>) {
        let mut vars = vec![format!("w_{}", copy.suffix())];
        let mut conds = vec![format!("0 <= w_{} < {}", copy.suffix(), self.body.width)];
        for (idx, l) in self.loops_of(access) {
            let k = format!("k{idx}_{}", copy.suffix());
            vars.push(k.clone());
            conds.push(format!("{k} >= 0"));
            let lo = self.term(&l.lo, copy);
            let hi = self.term(&l.hi, copy);
            let step = self.term(&l.step, copy);
            conds.push(format!("({lo} + {step} * {k}) < {hi}"));
        }
        for hv in &access.havoc {
            vars.push(format!("{hv}_{}", copy.suffix()));
        }
        (vars, conds)
    }

    // Q1/Q2 numbering and copy letters are necessities.
    #[allow(inline_literal)]
    fn pair_goals(&mut self) {
        let pairs: Vec<(usize, usize)> = self
            .body
            .accesses
            .iter()
            .enumerate()
            .flat_map(|(i, a)| {
                self.body
                    .accesses
                    .iter()
                    .enumerate()
                    .map(move |(j, b)| (i, j, a, b))
            })
            .filter(|(i, j, a, b)| j > i && a.region == b.region && touching(a.dir, b.dir))
            .map(|(i, j, _, _)| (i, j))
            .collect();
        if pairs.is_empty() {
            let _ = writeln!(
                self.out,
                "  (* no unordered read/write or write/write pairs on one region *)"
            );
            let _ = writeln!(self.out);
            return;
        }
        for (i, j) in pairs {
            let a = &self.body.accesses[i];
            let b = &self.body.accesses[j];
            self.goal_seq += 1;
            let kind = if matches!((a.dir, b.dir), (Dir::Write, Dir::Write)) {
                tool::GOAL_WAW
            } else {
                tool::GOAL_RAW
            };
            let name = format!("{kind}_{}_n{}", sanitize(&a.region), self.goal_seq);
            if a.offsets.len() != a.shapes.len() || b.offsets.len() != b.shapes.len()
                || a.offsets.len() != b.offsets.len()
            {
                let _ = writeln!(
                    self.out,
                    "  (* {name}: SKIPPED — window ranks mismatch on {} *)",
                    a.region
                );
                let _ = writeln!(self.out);
                continue;
            }
            let (vars_a, conds_a) = self.instance(a, Copy::A);
            let (vars_b, conds_b) = self.instance(b, Copy::B);
            let all_conds = [conds_a.clone(), conds_b.clone()].concat();
            // Drop quantifiers the goal body never mentions (why3 leaves
            // unused quantified variables polymorphic).
            let body_text = format!(
                "{} w_a <> w_b {} {} {}",
                all_conds.join(" "),
                self.bool_str(&a.guards, Copy::A),
                self.bool_str(&b.guards, Copy::B),
                self.overlap_str(a, b)
            );
            let all_vars: Vec<String> = [vars_a, vars_b]
                .concat()
                .into_iter()
                .filter(|v| body_text.contains(v.as_str()) || all_conds.iter().any(|c| c.contains(v.as_str())))
                .collect();
            let _ = writeln!(
                self.out,
                "  (* Q{}: {} on {} (log entries {} and {}) *)",
                if kind == tool::GOAL_WAW { 2 } else { 1 },
                kind,
                a.region,
                i + 1,
                j + 1
            );
            let _ = writeln!(self.out, "  goal {name} : forall {} .", all_vars.join(" "));
            for cond in &all_conds {
                let _ = writeln!(self.out, "    {cond} ->");
            }
            let _ = writeln!(self.out, "    w_a <> w_b ->");
            let _ = writeln!(
                self.out,
                "    not ({} /\\ {} /\\ {})",
                self.bool_str(&a.guards, Copy::A),
                self.bool_str(&b.guards, Copy::B),
                self.overlap_str(a, b)
            );
            let _ = writeln!(self.out);
        }
    }

    fn overlap_str(&self, a: &Access, b: &Access) -> String {
        let mut parts = Vec::new();
        for (dim, ((o1, s1), (o2, s2))) in a
            .offsets
            .iter()
            .zip(&a.shapes)
            .zip(b.offsets.iter().zip(&b.shapes))
            .enumerate()
        {
            let _ = dim;
            parts.push(format!(
                "overlap {} {} {} {}",
                self.term(o1, Copy::A),
                self.term(s1, Copy::A),
                self.term(o2, Copy::B),
                self.term(s2, Copy::B)
            ));
        }
        parts.join(crate::consts::SEP_WHY3_AND)
    }

    // WhyML operator spellings and Q3 numbering are necessities.
    #[allow(inline_literal)]
    fn coverage_goals(&mut self) {
        if !self.body.havocs.is_empty() {
            let _ = writeln!(
                self.out,
                "  (* Q3: SKIPPED — body carries state; havoced contexts cannot prove coverage *)"
            );
            let _ = writeln!(self.out);
            return;
        }
        let mut regions: Vec<&str> = Vec::new();
        for access in &self.body.accesses {
            if access.dir == Dir::Write && !regions.contains(&access.region.as_str()) {
                regions.push(&access.region);
            }
        }
        for region in regions {
            self.goal_seq += 1;
            let writes: Vec<&Access> = self
                .body
                .accesses
                .iter()
                .filter(|a| a.dir == Dir::Write && a.region == region)
                .collect();
            let Some(first) = writes.first() else {
                continue;
            };
            let rank = first.offsets.len();
            let mut dims_ok = true;
            let mut dim_names = Vec::new();
            for axis in 0..rank {
                let name = format!("{}{}_{}", tool::DIM_PREFIX, sanitize(region), axis);
                if self.body.consts.iter().any(|(n, _)| *n == name) {
                    dim_names.push(name);
                } else {
                    dims_ok = false;
                }
            }
            let dvars: Vec<String> = (0..rank).map(|d| format!("d{d}")).collect();
            let name = format!("covered_{}_n{}", sanitize(region), self.goal_seq);
            if !dims_ok {
                let _ = writeln!(
                    self.out,
                    "  (* Q3 {name}: SKIPPED — region {region} has non-literal dims *)"
                );
                let _ = writeln!(self.out);
                continue;
            }
            let _ = writeln!(
                self.out,
                "  (* Q3: every datum of {region} is written by some tile *)"
            );
            let _ = writeln!(self.out, "  goal {name} : forall {} .", dvars.join(" "));
            for axis in 0..rank {
                let _ = writeln!(
                    self.out,
                    "    0 <= {} < {} ->",
                    dvars[axis], dim_names[axis]
                );
            }
            let mut exists_parts = Vec::new();
            for w in &writes {
                let (vars, conds) = self.instance(w, Copy::A);
                let mut cover = Vec::new();
                for (axis, (o, s)) in w.offsets.iter().zip(&w.shapes).enumerate() {
                    cover.push(format!(
                        "{} <= {} < {} + {}",
                        self.term(o, Copy::A),
                        dvars[axis],
                        self.term(o, Copy::A),
                        self.term(s, Copy::A)
                    ));
                }
                exists_parts.push(format!(
                    "(exists {} . {} /\\ {} /\\ {})",
                    vars.join(" "),
                    conds.join(" /\\ "),
                    self.bool_str(&w.guards, Copy::A),
                    cover.join(" /\\ ")
                ));
            }
            let _ = writeln!(self.out, "    {}", exists_parts.join(" \\/ "));
            let _ = writeln!(self.out);
        }
    }

    fn finish(&mut self) -> String {
        let _ = writeln!(self.out, "end");
        self.out.clone()
    }

    fn term(&self, t: &Term, copy: Copy) -> String {
        match t {
            Term::Int(n) => format!("{n}"),
            Term::Var(name) => match self.body.loops.iter().enumerate().find(|(_, l)| &l.var == name) {
                Some((idx, l)) => format!(
                    "({} + {} * k{idx}_{})",
                    self.term(&l.lo, copy),
                    self.term(&l.step, copy),
                    copy.suffix()
                ),
                // Havoced writer-context symbols are quantified per copy.
                None if self.body.havocs.contains(name) => {
                    format!("{}_{}", sanitize(name), copy.suffix())
                }
                None => sanitize(name),
            },
            Term::Bin(op, a, b) => {
                let (x, y) = (self.term(a, copy), self.term(b, copy));
                match op {
                    BinOp::Div => format!("(ComputerDivision.div {x} {y})"),
                    BinOp::Mod => format!("(ComputerDivision.mod {x} {y})"),
                    BinOp::Add => format!("({x} + {y})"),
                    BinOp::Sub => format!("({x} - {y})"),
                    BinOp::Mul => format!("({x} * {y})"),
                }
            }
            Term::Min(a, b) => format!("(MinMax.min {} {})", self.term(a, copy), self.term(b, copy)),
            Term::Max(a, b) => format!("(MinMax.max {} {})", self.term(a, copy), self.term(b, copy)),
            Term::Read { func, args } => {
                let rendered: Vec<String> =
                    args.iter().map(|a| self.term(a, copy)).collect();
                format!("({} {})", sanitize(func), rendered.join(" "))
            }
            Term::BlockIdx => format!("w_{}", copy.suffix()),
        }
    }

    // WhyML operator spellings and Q3 numbering are necessities.
    #[allow(inline_literal)]
    fn bool_str(&self, b: &Bool, copy: Copy) -> String {
        match b {
            Bool::B(true) => "true".to_owned(),
            Bool::B(false) => "false".to_owned(),
            Bool::Cmp(op, a, c) => format!(
                "({} {} {})",
                self.term(a, copy),
                match op {
                    CmpOp::Lt => "<",
                    CmpOp::Le => "<=",
                    CmpOp::Gt => ">",
                    CmpOp::Ge => ">=",
                    CmpOp::Eq => "=",
                    CmpOp::Ne => "<>",
                },
                self.term(c, copy)
            ),
            Bool::Not(inner) => format!("(not {})", self.bool_str(inner, copy)),
            Bool::And(parts) => self.join(parts, copy, "/\\"),
            Bool::Or(parts) => self.join(parts, copy, "\\/"),
        }
    }

    // WhyML operator spellings and Q3 numbering are necessities.
    #[allow(inline_literal)]
    fn join(&self, parts: &[Bool], copy: Copy, sep: &str) -> String {
        let rendered: Vec<String> = parts.iter().map(|p| self.bool_str(p, copy)).collect();
        format!("({})", rendered.join(&format!(" {sep} ")))
    }
}

fn touching(a: Dir, b: Dir) -> bool {
    matches!((a, b), (Dir::Write, Dir::Write) | (Dir::Read, Dir::Write) | (Dir::Write, Dir::Read))
}
