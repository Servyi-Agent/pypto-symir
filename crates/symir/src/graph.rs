//! Graph construction and drawing, backed by [petgraph].
//!
//! The [`TaskDag`] is mapped onto a `petgraph::DiGraph`; all drawing goes
//! through libraries: `petgraph::dot::Dot` generates the layout
//! description, and graphviz renders it (`--emit svg|png`). Nothing here
//! hand-formats graph output — when the picture looks wrong, the mapping
//! is wrong, and that follows the repository regression rule.
//!
//! [petgraph]: https://crates.io/crates/petgraph

use std::env;
use std::fs;
use std::io::Write;
use std::path::Path;
use std::process::Command;

use petgraph::dot::Dot;
use petgraph::graph::NodeIndex;
use petgraph::{Directed, Graph};

use crate::consts;
use crate::dag::{EdgeKind, TaskDag};
use crate::error::SymirError;

/// The petgraph view of a task DAG: nodes carry labels, edges carry tags.
pub struct TaskGraph {
    graph: Graph<String, String, Directed>,
}

/// Builds the petgraph representation of `dag`.
pub fn build(dag: &TaskDag) -> TaskGraph {
    let mut graph = Graph::new();
    let mut indices = Vec::new();
    for node in &dag.nodes {
        let header = match node.kind {
            crate::dag::NodeKind::Host => consts::GRAPH_KIND_HOST.to_owned(),
            _ => node.label.clone(),
        };
        let reads = region_list(dag, &node.reads.iter().copied().collect::<Vec<_>>());
        let writes = region_list(dag, &node.writes.iter().copied().collect::<Vec<_>>());
        let iters = node
            .iter_ctx
            .iter()
            .map(|i| i.var.clone())
            .collect::<Vec<_>>()
            .join(consts::SEP_COMMA_SPACE);
        // Real newline characters: graphviz renders them as line breaks
        // in quoted labels, while the two-character escape sequence would
        // survive petgraph's escaper as literal text (observed, red-tested
        // in tests/graph.rs).
        let nl = consts::LABEL_NEWLINE;
        let mut label = format!("{header}{nl}R:[{reads}] W:[{writes}]");
        if !iters.is_empty() {
            label = format!("{label}{nl}iter: {iters}");
        }
        if !node.guards.is_empty() {
            label = format!("{label}{nl}when: {}", node.guards.join(consts::SEP_GUARD));
        }
        indices.push(graph.add_node(label));
    }
    for edge in &dag.edges {
        let Some(from) = indices.get(edge.from) else {
            continue;
        };
        let Some(to) = indices.get(edge.to) else {
            continue;
        };
        let regions = region_list(dag, &edge.regions);
        let tag = match edge.kind {
            EdgeKind::Dep => consts::EDGE_TAG_DEP.to_owned(),
            EdgeKind::Raw => format!("{} [{regions}]", consts::EDGE_TAG_RAW),
            EdgeKind::Waw => format!("{} [{regions}]", consts::EDGE_TAG_WAW),
            EdgeKind::War => format!("{} [{regions}]", consts::EDGE_TAG_WAR),
            EdgeKind::Race => format!("{} [{regions}]", consts::EDGE_TAG_RACE),
        };
        let _ = graph.add_edge(*from, *to, tag);
    }
    TaskGraph { graph }
}

impl TaskGraph {
    /// The DOT layout description, generated by petgraph. Node and edge
    /// weights carry the labels; petgraph escapes them.
    pub fn to_dot(&self, name: &str) -> String {
        let _ = name; // petgraph emits an anonymous digraph; see README.
        Dot::new(&self.graph).to_string()
    }

    /// True when the graph is a DAG (petgraph toposort succeeds) — the
    /// acyclicity half of the structural assertions.
    pub fn is_acyclic(&self) -> bool {
        petgraph::algo::toposort(&self.graph, None).is_ok()
    }

    /// Renders through graphviz into `format` (`svg` or `png`), writing to
    /// `output`.
    pub fn render(&self, name: &str, output_format: &str, output: &Path) -> Result<(), SymirError> {
        let dot_source = self.to_dot(name);
        let prefix = consts::DOT_TEMP_PREFIX;
        let safe = sanitize(name);
        let mut dot_path = env::temp_dir();
        dot_path.push(format!("{prefix}{safe}.dot"));
        if let Some(parent) = dot_path.parent() {
            let _ = fs::create_dir_all(parent);
        }
        let mut file = fs::File::create(&dot_path).map_err(|e| SymirError::Interp {
            line: 0,
            message: format!("cannot write {dot_path:?}: {e}"),
        })?;
        let _ = file.write_all(dot_source.as_bytes());
        let rendered = Command::new(consts::GRAPHVIZ_DOT)
            .arg(format!("-T{output_format}"))
            .arg(&dot_path)
            .arg(consts::GRAPHVIZ_OUTPUT_FLAG)
            .arg(output)
            .status()
            .map_err(|e| SymirError::Interp {
                line: 0,
                message: format!(
                    "graphviz ({}) is required for --emit svg/png: {e}",
                    consts::GRAPHVIZ_DOT
                ),
            })?;
        let _ = fs::remove_file(&dot_path);
        if !rendered.success() {
            return Err(SymirError::Interp {
                line: 0,
                message: format!("graphviz exited with {rendered}"),
            });
        }
        Ok(())
    }

    /// Node count of the underlying graph (for tests).
    pub fn node_count(&self) -> usize {
        self.graph.node_count()
    }

    /// Edge count of the underlying graph (for tests).
    pub fn edge_count(&self) -> usize {
        self.graph.edge_count()
    }

    /// Direct successor check (for tests).
    pub fn connects(&self, from: usize, to: usize) -> bool {
        self.graph
            .contains_edge(NodeIndex::new(from), NodeIndex::new(to))
    }
}

/// Comma-joined region names.
fn region_list(dag: &TaskDag, regions: &[usize]) -> String {
    regions
        .iter()
        .map(|r| {
            dag.regions
                .get(*r)
                .cloned()
                .unwrap_or_else(|| format!("R{r}"))
        })
        .collect::<Vec<_>>()
        .join(consts::SEP_COMMA_SPACE)
}

/// Keeps a filesystem-safe fragment of the program name.
fn sanitize(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == consts::NAME_SAFE_DOT {
                c
            } else {
                consts::NAME_SAFE_FALLBACK
            }
        })
        .collect()
}
